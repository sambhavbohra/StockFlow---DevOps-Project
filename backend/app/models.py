"""Tables from docs/05-backend-schema.md. Rules the database can enforce are enforced here too."""
from datetime import datetime
from decimal import Decimal

from sqlalchemy import (
    CheckConstraint, Computed, ForeignKey, Identity, MetaData, Numeric, String, Text, func,
)
from sqlalchemy.dialects.postgresql import CHAR
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship
from sqlalchemy.types import DateTime

# Stable constraint names so Alembic migrations stay predictable.
NAMING = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

ORDER_STATUSES = ("PENDING", "CONFIRMED", "SHIPPED", "DELIVERED", "CANCELLED")


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING)


def created_at() -> Mapped[datetime]:
    return mapped_column(DateTime(timezone=True), server_default=func.now())


def updated_at() -> Mapped[datetime]:
    return mapped_column(DateTime(timezone=True), server_default=func.now(), onupdate=func.now())


class Product(Base):
    __tablename__ = "products"
    __table_args__ = (
        CheckConstraint("unit_price >= 0", name="unit_price_non_negative"),
        CheckConstraint("quantity_on_hand >= 0", name="quantity_non_negative"),
        CheckConstraint("reorder_threshold >= 0", name="reorder_threshold_non_negative"),
        CheckConstraint("length(trim(name)) > 0", name="name_not_blank"),
        CheckConstraint("length(trim(sku)) > 0", name="sku_not_blank"),
    )

    id: Mapped[int] = mapped_column(Identity(), primary_key=True)
    name: Mapped[str] = mapped_column(String(120))
    sku: Mapped[str] = mapped_column(String(64), unique=True)
    category: Mapped[str] = mapped_column(String(60), server_default="General")
    description: Mapped[str | None] = mapped_column(Text)
    unit_price: Mapped[Decimal] = mapped_column(Numeric(12, 2))
    quantity_on_hand: Mapped[int] = mapped_column(server_default="0")
    reorder_threshold: Mapped[int] = mapped_column(server_default="10")
    is_active: Mapped[bool] = mapped_column(server_default="true", index=True)
    created_at: Mapped[datetime] = created_at()
    updated_at: Mapped[datetime] = updated_at()


class InventoryMovement(Base):
    __tablename__ = "inventory_movements"
    __table_args__ = (
        CheckConstraint("movement_type IN ('IN', 'OUT')", name="movement_type_valid"),
        CheckConstraint("quantity > 0", name="quantity_positive"),
        CheckConstraint("quantity_before >= 0 AND quantity_after >= 0", name="quantities_non_negative"),
        CheckConstraint("reference_type IN ('MANUAL', 'ORDER')", name="reference_type_valid"),
    )

    id: Mapped[int] = mapped_column(Identity(), primary_key=True)
    product_id: Mapped[int] = mapped_column(ForeignKey("products.id", ondelete="RESTRICT"), index=True)
    movement_type: Mapped[str] = mapped_column(String(3))
    quantity: Mapped[int]
    reason: Mapped[str] = mapped_column(String(120))
    notes: Mapped[str | None] = mapped_column(Text)
    quantity_before: Mapped[int]
    quantity_after: Mapped[int]
    reference_type: Mapped[str] = mapped_column(String(10), server_default="MANUAL")
    reference_id: Mapped[int | None]
    created_at: Mapped[datetime] = created_at()

    product: Mapped[Product] = relationship()


class Order(Base):
    __tablename__ = "orders"
    __table_args__ = (
        CheckConstraint(f"status IN {ORDER_STATUSES}", name="status_valid"),
        CheckConstraint("subtotal >= 0", name="subtotal_non_negative"),
    )

    id: Mapped[int] = mapped_column(Identity(), primary_key=True)
    # Generated by PostgreSQL from the id, so it is always unique and never client-supplied.
    order_number: Mapped[str] = mapped_column(
        String(20), Computed("'ORD-' || lpad(id::text, 4, '0')", persisted=True), unique=True
    )
    customer_name: Mapped[str] = mapped_column(String(120))
    status: Mapped[str] = mapped_column(String(10), server_default="PENDING", index=True)
    subtotal: Mapped[Decimal] = mapped_column(Numeric(12, 2), server_default="0")
    currency: Mapped[str] = mapped_column(CHAR(3), server_default="INR")
    created_at: Mapped[datetime] = created_at()
    updated_at: Mapped[datetime] = updated_at()
    confirmed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    cancelled_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    items: Mapped[list["OrderItem"]] = relationship(back_populates="order", cascade="all, delete-orphan")


class OrderItem(Base):
    __tablename__ = "order_items"
    __table_args__ = (
        CheckConstraint("quantity > 0", name="quantity_positive"),
        CheckConstraint("unit_price >= 0", name="unit_price_non_negative"),
    )

    id: Mapped[int] = mapped_column(Identity(), primary_key=True)
    order_id: Mapped[int] = mapped_column(ForeignKey("orders.id", ondelete="CASCADE"), index=True)
    product_id: Mapped[int] = mapped_column(ForeignKey("products.id", ondelete="RESTRICT"), index=True)
    product_name_snapshot: Mapped[str] = mapped_column(String(120))
    sku_snapshot: Mapped[str] = mapped_column(String(64))
    quantity: Mapped[int]
    unit_price: Mapped[Decimal] = mapped_column(Numeric(12, 2))
    line_total: Mapped[Decimal] = mapped_column(Numeric(12, 2))

    order: Mapped[Order] = relationship(back_populates="items")


class AppSettings(Base):
    __tablename__ = "app_settings"
    __table_args__ = (CheckConstraint("id = 1", name="single_row"),)

    id: Mapped[int] = mapped_column(primary_key=True, server_default="1")
    business_name: Mapped[str] = mapped_column(String(80), server_default="StockFlow Demo Store")
    updated_at: Mapped[datetime] = updated_at()
